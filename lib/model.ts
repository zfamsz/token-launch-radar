// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// rankable pre-token protocol below the watchlist floor: the early rows the radar exists to find.
// A protocol is pre-token when its index entry records no token (no market cap, no CoinGecko id, no
// symbol); the snapshot's live-token protocols are kept apart and shown as the market's own values,
// never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and never from a hand-written list of
// names. The multiple a protocol gets is not a constant: it is the median market-cap-to-TVL ratio of
// the live-token protocols in its own category, computed from this same snapshot. A category with
// fewer than three live comparables falls back to the global median. That is the model's whole claim:
// a protocol is worth what the market already pays for the same kind of protocol, per dollar of TVL,
// scaled by its own growth and by how long it has run with no token.
//
//   multiple     = median(mcap_usd / tvl_usd) over live-token protocols in the category
//                  (at least 3 comparables, else the global median), clamped to [0.05, 1.50]
//   growth       = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied      = max(1, round(tvl_usd x multiple x growthMult x maturity))
//
// The constants are the model's, stated in the dashboard and changeable in the model sandbox. No
// protocol name is ever special-cased: the same function scores every row.

